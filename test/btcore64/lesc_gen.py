"""Makes Sources/Networking/Bluetooth/test/btcore/lesc_vectors.inc: an LE Secure Connections pairing
transcript (just works, and passkey entry) worked out with OpenSSL through
Python's `cryptography` package, from the formulas in Bluetooth Core Spec
Vol 3 Part H 2.2 (f4, f5, f6) written out here independently of
Sources/Networking/Bluetooth/c/le_crypto.c.

The host check (lesc.c) plays the device's part from this canned data and
compares what the stack sends with what is computed here, so a mistake in
byte order, in the address arguments or in the IO capability octets of the
stack cannot be shared with the data.

Spec values are most significant octet first; SMP PDUs and HCI carry them
least significant first, so everything that goes on the wire is reversed.
"""
import sys
from cryptography.hazmat.primitives.asymmetric import ec
from cryptography.hazmat.primitives.cmac import CMAC
from cryptography.hazmat.primitives.ciphers import algorithms


def cmac(k, m):
    c = CMAC(algorithms.AES(k))
    c.update(m)
    return c.finalize()


def rev(b):
    return bytes(reversed(b))


def f4(u, v, x, z):
    return cmac(x, u + v + bytes([z]))


SALT = bytes.fromhex("6c888391aaf5a53860370bdb5a6083be")


def f5(w, n1, n2, a1, a2):
    t = cmac(SALT, w)
    def block(c):
        return cmac(t, bytes([c]) + b"btle" + n1 + n2 + a1 + a2 + b"\x01\x00")
    return block(0), block(1)          # MacKey, LTK


def f6(w, n1, n2, r, iocap, a1, a2):
    return cmac(w, n1 + n2 + r + iocap + a1 + a2)


def stream(k):
    """The fake controller's LE Rand stream (the C test makes the same)."""
    return bytes((i * 37 + 11) & 0xff for i in range(k))


def c_array(name, b, per=12):
    out = ["static const uint8_t %s[%d] = {" % (name, len(b))]
    for i in range(0, len(b), per):
        out.append("\t" + ", ".join("0x%02x" % x for x in b[i:i + per]) + ",")
    out.append("};")
    return "\n".join(out)


# Addresses as HCI carries them (LSB first); the spec's A1/A2 are
# address type then the address most significant octet first.
OUR_ADDR = bytes([0x06, 0x05, 0x04, 0x03, 0x02, 0x01])
PEER_ADDR = bytes([0x66, 0x55, 0x44, 0x33, 0x22, 0x11])
PEER_TYPE = 1                          # random
A1 = bytes([0]) + rev(OUR_ADDR)        # initiator: us, public
A2 = bytes([PEER_TYPE]) + rev(PEER_ADDR)

rnd = stream(48)
priv_a = int.from_bytes(rnd[0:32], "little")
seed = rnd[32:48]
key_a = ec.derive_private_key(priv_a, ec.SECP256R1())
key_b = ec.derive_private_key(
    int("1b4f0a5c97d3e20718c6a94be1f0d5238a7c4e69b03d1f52a6e8c07d49b3f1e5", 16),
    ec.SECP256R1())


def lsb_xy(k):
    n = k.public_key().public_numbers()
    return rev(n.x.to_bytes(32, "big")) + rev(n.y.to_bytes(32, "big"))


def xs(k):
    return k.public_key().public_numbers().x.to_bytes(32, "big")


pka_x, pkb_x = xs(key_a), xs(key_b)
dh = key_a.exchange(ec.ECDH(), key_b.public_key())     # big-endian X


def nonce_a(i):
    return cmac(seed, b"N" + bytes([i]))     # the stack's own derivation


def nonce_b(i):
    return bytes((i * 13 + j * 5 + 3) & 0xff for j in range(16))


def keys_and_checks(na, nb, r, preq_io, pres_io):
    # na, nb: as on the wire (LSB first); the spec wants them MSB first.
    mac, ltk = f5(dh, rev(na), rev(nb), A1, A2)
    ea = f6(mac, rev(na), rev(nb), r, preq_io, A1, A2)
    eb = f6(mac, rev(nb), rev(na), r, pres_io, A2, A1)
    return mac, ltk, ea, eb


out = []
out.append("/* Generated by lesc_gen.py: do not edit. */")
out.append(c_array("sc_pka", lsb_xy(key_a)))
out.append(c_array("sc_pkb", lsb_xy(key_b)))

# --- just works. Pairing Request 01 00 00 09 10 00 03: IO DisplayOnly,
# no OOB, bonding + SC, key size 16; Response 02 03 00 09 10 00 03: the
# device has no input or output (NoInputNoOutput).
preq_io = bytes([0x09, 0x00, 0x00])        # AuthReq || OOB || IOcap
pres_io = bytes([0x09, 0x00, 0x03])
na = nonce_a(0)
nb = nonce_b(99)
cb = rev(f4(pkb_x, pka_x, rev(nb), 0))
mac, ltk, ea, eb = keys_and_checks(na, nb, bytes(16), preq_io, pres_io)
out.append(c_array("jw_na", na))
out.append(c_array("jw_nb", nb))
out.append(c_array("jw_cb", cb))
out.append(c_array("jw_ea", rev(ea)))
out.append(c_array("jw_eb", rev(eb)))
out.append(c_array("jw_ltk", rev(ltk)))

# --- passkey entry: the device has a keyboard (KeyboardOnly 2), MITM.
pres_io_pk = bytes([0x0d, 0x00, 0x02])
preq_io_pk = preq_io
tag = cmac(seed, b"P")
passkey = (tag[0] | tag[1] << 8 | tag[2] << 16) & 0xfffff
if passkey >= 1000000:
    passkey -= 1000000
out.append("#define PK_PASSKEY %du" % passkey)
cas, nas, cbs, nbs = [], [], [], []
for i in range(20):
    z = 0x80 | ((passkey >> i) & 1)
    n_a, n_b = nonce_a(i), nonce_b(i)
    cas.append(rev(f4(pka_x, pkb_x, rev(n_a), z)))
    nas.append(n_a)
    cbs.append(rev(f4(pkb_x, pka_x, rev(n_b), z)))
    nbs.append(n_b)
r = passkey.to_bytes(16, "big")
mac, ltk, ea, eb = keys_and_checks(nas[19], nbs[19], r, preq_io_pk, pres_io_pk)
out.append(c_array("pk_ca", b"".join(cas), 16))
out.append(c_array("pk_na", b"".join(nas), 16))
out.append(c_array("pk_cb", b"".join(cbs), 16))
out.append(c_array("pk_nb", b"".join(nbs), 16))
out.append(c_array("pk_ea", rev(ea)))
out.append(c_array("pk_eb", rev(eb)))
out.append(c_array("pk_ltk", rev(ltk)))

# --- legacy just works, as the MX Master does it (its Pairing Response
# was 02 03 00 01 10 02 03: NoInputNoOutput, bonding, no SC, key size 16).
from cryptography.hazmat.primitives.ciphers import Cipher, modes
def e(k, d):
    return Cipher(algorithms.AES(k), modes.ECB()).encryptor().update(d)
def xor(a, b):
    return bytes(x ^ y for x, y in zip(a, b))
def c1(k, r, preq, pres, iat, ia, rat, ra):
    p1 = rev(pres) + rev(preq) + bytes([rat]) + bytes([iat])
    p2 = bytes(4) + rev(ia) + rev(ra)
    return e(k, xor(e(k, xor(r, p1)), p2))
def s1(k, r1, r2):
    return e(k, r1[8:] + r2[8:])
TK = bytes(16)
preq = bytes.fromhex("01000009100303")
pres = bytes.fromhex("02030001100203")
mrand = stream(16)                       # the first two LE Rand results
srand = bytes((0xa0 + i * 3) & 0xff for i in range(16))
mconf = c1(TK, rev(mrand), preq, pres, 0, OUR_ADDR, PEER_TYPE, PEER_ADDR)
sconf = c1(TK, rev(srand), preq, pres, 0, OUR_ADDR, PEER_TYPE, PEER_ADDR)
stk = s1(TK, rev(srand), rev(mrand))     # STK = s1(TK, Srand, Mrand)
wrong = s1(TK, rev(mrand), rev(srand))   # the order that was used by mistake
out.append(c_array("lg_mrand", mrand))
out.append(c_array("lg_srand", srand))
out.append(c_array("lg_mconfirm", rev(mconf)))
out.append(c_array("lg_sconfirm", rev(sconf)))
out.append(c_array("lg_stk", rev(stk)))
out.append(c_array("lg_stk_wrong", rev(wrong)))

# A wrong DHKey check must be refused: the same with one bit changed is
# made in the C test.
open(sys.argv[1] if len(sys.argv) > 1 else "lesc_vectors.inc", "w").write(
    "\n".join(out) + "\n")
